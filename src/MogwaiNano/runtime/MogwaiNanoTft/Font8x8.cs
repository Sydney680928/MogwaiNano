        private static readonly byte[] LowerOe = new byte[] { 0x00, 0x00, 0x66, 0x99, 0xF9, 0x19, 0x66, 0x00 };
        private static readonly byte[] UpperOe = new byte[] { 0xF6, 0x19, 0x19, 0x79, 0x19, 0x19, 0xF6, 0x00 };
        private static readonly byte[] Degree = new byte[] { 0x0C, 0x12, 0x12, 0x0C, 0x00, 0x00, 0x00, 0x00 };
        private static readonly byte[] Laquo = new byte[] { 0x00, 0x00, 0x24, 0x12, 0x09, 0x12, 0x24, 0x00 };
        private static readonly byte[] Raquo = new byte[] { 0x00, 0x00, 0x09, 0x12, 0x24, 0x12, 0x09, 0x00 };
        private static readonly byte[] Euro = new byte[] { 0x1C, 0x22, 0x0F, 0x01, 0x0F, 0x22, 0x1C, 0x00 };
        private static readonly byte[] MidDot = new byte[] { 0x00, 0x00, 0x00, 0x0C, 0x0C, 0x00, 0x00, 0x00 };

        /// <summary>Remplit dst (8 octets) avec le glyphe du caractere c.</summary>
        public static void GetGlyph(char c, byte[] dst)
        {
            if (c >= 32 && c <= 126)
            {
                Array.Copy(Basic, (c - 32) * 8, dst, 0, 8);
                return;
            }

            switch (c)
            {
                // minuscules accentuees
                case '\u00E0': Compose('a', Grave, dst); return;       // a grave
                case '\u00E1': Compose('a', Acute, dst); return;       // a aigu
                case '\u00E2': Compose('a', Circumflex, dst); return;  // a circonflexe
                case '\u00E4': Compose('a', Diaeresis, dst); return;   // a trema
                case '\u00E7': Compose('c', Cedilla, dst); return;     // c cedille
                case '\u00E8': Compose('e', Grave, dst); return;       // e grave
                case '\u00E9': Compose('e', Acute, dst); return;       // e aigu
                case '\u00EA': Compose('e', Circumflex, dst); return;  // e circonflexe
                case '\u00EB': Compose('e', Diaeresis, dst); return;   // e trema
                case '\u00ED': Compose('i', Acute, dst); return;       // i aigu
                case '\u00EE': Compose('i', Circumflex, dst); return;  // i circonflexe
                case '\u00EF': Compose('i', Diaeresis, dst); return;   // i trema
                case '\u00F3': Compose('o', Acute, dst); return;       // o aigu
                case '\u00F4': Compose('o', Circumflex, dst); return;  // o circonflexe
                case '\u00F6': Compose('o', Diaeresis, dst); return;   // o trema
                case '\u00F9': Compose('u', Grave, dst); return;       // u grave
                case '\u00FA': Compose('u', Acute, dst); return;       // u aigu
                case '\u00FB': Compose('u', Circumflex, dst); return;  // u circonflexe
                case '\u00FC': Compose('u', Diaeresis, dst); return;   // u trema
                case '\u00FF': Compose('y', Diaeresis, dst); return;   // y trema

                // majuscules accentuees
                case '\u00C0': Compose('A', Grave, dst); return;
                case '\u00C2': Compose('A', Circumflex, dst); return;
                case '\u00C4': Compose('A', Diaeresis, dst); return;
                case '\u00C7': Compose('C', Cedilla, dst); return;
                case '\u00C8': Compose('E', Grave, dst); return;
                case '\u00C9': Compose('E', Acute, dst); return;
                case '\u00CA': Compose('E', Circumflex, dst); return;
                case '\u00CB': Compose('E', Diaeresis, dst); return;
                case '\u00CE': Compose('I', Circumflex, dst); return;
                case '\u00CF': Compose('I', Diaeresis, dst); return;
                case '\u00D4': Compose('O', Circumflex, dst); return;
                case '\u00D6': Compose('O', Diaeresis, dst); return;
                case '\u00D9': Compose('U', Grave, dst); return;
                case '\u00DB': Compose('U', Circumflex, dst); return;
                case '\u00DC': Compose('U', Diaeresis, dst); return;

                // ligatures et symboles
                case '\u0153': Array.Copy(LowerOe, 0, dst, 0, 8); return;  // oe
                case '\u0152': Array.Copy(UpperOe, 0, dst, 0, 8); return;  // OE
                case '\u00B0': Array.Copy(Degree, 0, dst, 0, 8); return;   // degre
                case '\u00AB': Array.Copy(Laquo, 0, dst, 0, 8); return;    // guillemet ouvrant
                case '\u00BB': Array.Copy(Raquo, 0, dst, 0, 8); return;    // guillemet fermant
                case '\u20AC': Array.Copy(Euro, 0, dst, 0, 8); return;     // euro
                case '\u00B7': Array.Copy(MidDot, 0, dst, 0, 8); return;   // point median

                // equivalents
                case '\u00A0': Array.Copy(Basic, 0, dst, 0, 8); return;                    // espace insecable
                case '\u2019': Array.Copy(Basic, ('\'' - 32) * 8, dst, 0, 8); return;      // apostrophe typographique
                case '\u2013': Array.Copy(Basic, ('-' - 32) * 8, dst, 0, 8); return;       // tiret demi-cadratin
            }

            // caractere inconnu
            Array.Copy(Basic, ('?' - 32) * 8, dst, 0, 8);
        }

        private static void Compose(char b, int accent, byte[] dst)
        {
            Array.Copy(Basic, (b - 32) * 8, dst, 0, 8);

            if (accent == Cedilla)
            {
                dst[7] = 0x0C;
                return;
            }

            bool upper = b >= 'A' && b <= 'Z';

            if (upper)
            {
                // Les majuscules occupent les lignes 0 a 6 : on descend d'une ligne
                // pour libérer la ligne 0, qui reçoit l'accent (1 ligne).
                for (int r = 7; r >= 1; r--)
                {
                    dst[r] = dst[r - 1];
                }

                switch (accent)
                {
                    case Acute: dst[0] = 0x18; break;
                    case Grave: dst[0] = 0x06; break;
                    case Circumflex: dst[0] = 0x1C; break;
                    default: dst[0] = 0x14; break;
                }
            }
            else
            {
                // Les minuscules sans hampe laissent libres les lignes 0 et 1 (accent sur 2 lignes).
                if (b == 'i')
                {
                    dst[0] = 0x00; // retire le point du i
                }

                switch (accent)
                {
                    case Acute: dst[0] |= 0x0C; dst[1] |= 0x06; break;
                    case Grave: dst[0] |= 0x06; dst[1] |= 0x0C; break;
                    case Circumflex: dst[0] |= 0x0C; dst[1] |= 0x12; break;
                    default: dst[0] |= 0x12; break;
                }
            }
        }
    }
